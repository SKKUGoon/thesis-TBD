import {test,expect} from '@playwright/test';
import {readFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
const bundle=process.env.DEMO_BUNDLE;
test('portable replay settings, loading, completed forecast and mobile',async({page})=>{
 test.skip(!bundle,'DEMO_BUNDLE is required');
 const token=readFileSync(resolve(bundle!,'private/access-token'),'utf8').trim();
 const evidence=resolve(bundle!,'../browser');mkdirSync(evidence,{recursive:true});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByLabel('접속 토큰',{exact:true}).fill(token);await page.getByRole('button',{name:'연결',exact:true}).click();
 await expect(page.getByTestId('forecast-count')).toContainText('420/420');
 await expect(page.getByTestId('patient-chart')).toBeVisible();
 await page.screenshot({path:resolve(evidence,'01-dashboard.png'),fullPage:true});
 await page.getByRole('button',{name:'업무 설정',exact:true}).click();
 await page.getByText('Demo Setting',{exact:true}).click();
 await page.getByLabel('시작 날짜',{exact:true}).selectOption('2024-03-11');
 await page.getByLabel('예측 로딩 시간 (초)',{exact:true}).fill('3');
 await page.screenshot({path:resolve(evidence,'02-settings.png'),fullPage:true});
 await page.getByRole('button',{name:'설정 적용',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'업무 설정',exact:true})).not.toBeVisible();
 await expect(page.getByTestId('forecast-count')).toContainText('420/420');
 const oldWorkspace=new URL(page.url()).searchParams.get('workspace');
 await page.getByRole('button',{name:'주간 자료 전달',exact:true}).click();
 await expect(page.locator('.forecast-loading')).toContainText('수신');
 await page.screenshot({path:resolve(evidence,'03-loading.png'),fullPage:true});
 await expect(page.getByTestId('forecast-count')).toContainText('420/420',{timeout:20000});
 await expect(page.locator('.current-key')).toContainText('03/18');
 await expect(page.locator('.prior-trace')).toHaveAttribute('d',/^M/);
 await page.screenshot({path:resolve(evidence,'04-completed.png'),fullPage:true});
 await page.reload();await page.getByLabel('접속 토큰',{exact:true}).fill(token);await page.getByRole('button',{name:'연결',exact:true}).click();
 await expect(page.getByTestId('forecast-count')).toContainText('420/420');
 expect(new URL(page.url()).searchParams.get('workspace')).toBe(oldWorkspace);
 await page.setViewportSize({width:390,height:1000});
 await expect(page.getByTestId('live-dashboard')).toHaveCount(1);
 await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))));
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:resolve(evidence,'05-mobile.png'),fullPage:true});
 await page.getByRole('button',{name:'업무 설정',exact:true}).click();await page.getByText('Demo Setting',{exact:true}).click();
 await expect(page.getByLabel('시작 날짜',{exact:true})).toHaveValue('2024-03-11');await expect(page.getByLabel('예측 로딩 시간 (초)',{exact:true})).toHaveValue('3');
 expect(errors).toEqual([]);
});
